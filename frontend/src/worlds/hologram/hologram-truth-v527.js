export function localHologramSocialReply(message) {
  const answer = SOCIAL[normalizeQuestion(message)];
  return answer ? {
    answer, speech: answer, speech_text: answer, presentations: [],
    source: 'local-social', route: 'local-social',
  } : null;
}

export function isLiveWorkforceQuestion(message) {
  const q = normalizeQuestion(message);
  if (!q) return false;
  // Require workforce + an explicit current shift or current-time qualifier.
  // A standalone 'gracias' or question about a past day cannot match.
  const workforce = /\b(trabajador(?:es)?|emplead(?:o|a|os|as)|personal|plantilla|gente|quien|quienes|cuantos|cuantas|personas)\b/u.test(q);
  const action = /\b(trabaj\w*|turno|servicio|fichad\w*|presentes?)\b/u.test(q);
  const current = /\b(ahora|actualmente|hoy|actual|mismo|este momento|en servicio|de turno|en turno|fichados?)\b/u.test(q);
  const historical = /\b(ayer|manana|la semana pasada|el mes pasado|en 2024|en 2025)\b/u.test(q);
  return workforce && action && current && !historical;
}

const SOURCE = /^(?:turnos|fichajes|asistencia|conectia|a3|roster|rostering|shift-engine|attendance)$/iu;

/**
 * Only machine-structured evidence from an operational route may authorize
 * a current headcount. Labels like `working_now` generated by an LLM do NOT.
 * Proposed evidence shape:
 * { data: { provenance: {
 *   source: 'turnos', scope:'working_now', coverage:'complete',
 *   as_of: ISO8601, working_count: integer
 * }}}.
 * Unsupported responses remain unverified, NOT automatically false.
 */
export function inspectLiveWorkforceProof(raw, route, now = Date.now(), question = '') {
  const reject = (reason) => ({ok:false,reason});
  if (!['backend-stream','backend-json'].includes(route)) return reject('route-not-operational');
  if (!isWorkforceRecord(raw)) return reject('not-object');
  const p = raw?.data?.provenance ?? raw?.provenance ?? raw?.data?.evidence ?? raw?.evidence;
  if (!isWorkforceRecord(p)) return reject('missing-source-proof');
  const source = String(p.source || p.system || '').toLowerCase().trim();
  if (!SOURCE.test(source)) return reject('unknown-source');
  const scope = String(p.scope || p.query_type || '').toLowerCase().trim();
  if (!['working_now','live_workforce','on_duty_now'].includes(scope)) return reject('wrong-scope');
  const complete = p.coverage === 'complete' || p.complete === true;
  if (!complete) return reject('partial-coverage');
  const asOfRaw = p.as_of ?? p.observed_at ?? p.timestamp;
  if (typeof asOfRaw !== 'string' || !/\d{4}-\d\d-\d\dT\d\d:\d\d/.test(asOfRaw)) return reject('no-timestamp');
  if (!/(?:Z|[+-]\d{2}:\d{2})$/i.test(asOfRaw)) return reject('timestamp-without-timezone');
  const asOf = Date.parse(asOfRaw);
  if (!Number.isFinite(asOf)) return reject('bad-timestamp');
  const ageMs = now - asOf;
  if (ageMs < -2 * 60_000 || ageMs > 10 * 60_000) return reject('stale-timestamp');
  // A department-specific count may not be presented as a global workforce KPI.
  const q = normalizeQuestion(question);
  const department = ['cocina','restaurante','mantenimiento','recepcion','pisos','limpieza','bar'].find((name) => q.includes(name));
  if (department && normalizeQuestion(p.department || '') !== department) return reject('department-mismatch');
  const count = p.working_count ?? p.total_working ?? p.count;
  if (!Number.isSafeInteger(count) || count < 0 || count > 100_000) return reject('missing-count');
  return {ok:true, source, asOf:asOfRaw, count, department:department || null, reason:'operational-proof'};
}

export function authoritativeWorkforceResponse(proof) {
  if (!proof?.ok) throw new Error('Invalid live workforce proof');
  const number = new Intl.NumberFormat('es-ES').format(proof.count);
  const scope = proof.department ? `en ${proof.department} hay` : 'hay';
  const answer = `Seg\u00fan ${proof.source}, ${scope} ${number} personas en servicio, con datos actualizados en esta consulta.`;
  const metricLabel = proof.department ? `En servicio - ${proof.department}` : 'Trabajando ahora';
  return {
    answer, speech:answer, speech_text:answer,
    working_now: proof.count,
    presentations: [{type:'metric',label:metricLabel,value:proof.count,unit:'personas'}],
    source:proof.source, as_of:proof.asOf, verified_live_workforce:true,
  };
}

export function unverifiedWorkforceResponse() {
  const answer = 'No puedo confirmar cu\u00e1ntas personas est\u00e1n trabajando ahora mismo: la respuesta recibida no incluye un recuento verificable de turnos o fichajes. Prefiero no darte una cifra incorrecta.';
  return {
    answer, speech:answer, speech_text:answer,
    presentations:[], source:'unverified-workforce',
    verified_live_workforce:false,
  };
}
